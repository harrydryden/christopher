#!/usr/bin/env node
/**
 * Regenerates packages/core/src/fonts/liberation-sans.ts, the "Arial" face of the CV renderer.
 *
 * Arial itself is proprietary, so the renderer embeds Liberation Sans, which is metric-compatible
 * with Arial and released under the SIL Open Font License 1.1. The bytes live in a TypeScript
 * module rather than a file on disk so that no bundler, serverless trace or working directory
 * can lose them, which is the same reason pdfkit ships its standard font metrics as modules.
 *
 * Usage: node scripts/embed-liberation-sans.mjs [directory holding LiberationSans-Regular.ttf and
 * LiberationSans-Bold.ttf]. The default is the Debian/Ubuntu fonts-liberation package location.
 */
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const directory = process.argv[2] ?? "/usr/share/fonts/truetype/liberation";
const output = new URL("../packages/core/src/fonts/liberation-sans.ts", import.meta.url);

function embed(file) {
  const bytes = readFileSync(path.join(directory, file));
  const base64 = bytes.toString("base64").match(/.{1,120}/g).join("\n");
  return { base64, bytes: bytes.length, sha256: createHash("sha256").update(bytes).digest("hex") };
}

const regular = embed("LiberationSans-Regular.ttf");
const bold = embed("LiberationSans-Bold.ttf");
const header = `// Generated by scripts/embed-liberation-sans.mjs. Do not edit by hand.
// Liberation Sans (SIL Open Font License 1.1; see LICENSE-LiberationSans.txt in this directory) is
// metric-compatible with Arial and is what the CV renderer embeds when the "Arial" font is chosen.
// LiberationSans-Regular.ttf: ${regular.bytes} bytes, sha256 ${regular.sha256}
// LiberationSans-Bold.ttf: ${bold.bytes} bytes, sha256 ${bold.sha256}
// Decode with Buffer.from(value.replace(/\\s+/g, ""), "base64").
`;
writeFileSync(
  output,
  `${header}export const LIBERATION_SANS_REGULAR = \`\n${regular.base64}\n\`;\n\nexport const LIBERATION_SANS_BOLD = \`\n${bold.base64}\n\`;\n`,
);
console.log(`wrote ${output.pathname}: regular ${regular.bytes} bytes, bold ${bold.bytes} bytes`);
